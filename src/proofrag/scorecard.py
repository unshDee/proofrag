"""Render a results dict into a self-contained, shareable HTML scorecard.

Zero external assets — inline CSS, no JS, no fonts fetched. Open the file
anywhere, attach it to a PR, drop it in CI artifacts. This is the artifact
people screenshot, so it is built to look good in light and dark mode.
"""

from __future__ import annotations

import html
from datetime import datetime

from . import __version__
from .judge import JUDGE_DIMENSIONS
from .metrics import RETRIEVAL_METRICS

_GEN_LABELS = {
    "groundedness": "Groundedness",
    "correctness": "Correctness",
    "completeness": "Completeness",
    "citation_quality": "Citation Quality",
    "faithfulness": "Faithfulness",
    "answer_relevancy": "Answer Relevancy",
    "relevancy": "Relevancy",
}

_GEN_SHORT = {
    "groundedness": "Grnd",
    "correctness": "Corr",
    "completeness": "Comp",
    "citation_quality": "Cite",
    "faithfulness": "Faith",
    "answer_relevancy": "Rel",
    "relevancy": "Rel",
}


def _gen_label(name: str) -> str:
    return _GEN_LABELS.get(name, name.replace("_", " ").title())


def _gen_short(name: str) -> str:
    return _GEN_SHORT.get(name, _gen_label(name)[:5])


def _gen_metrics(results: dict) -> list[str]:
    """Generation metric names for this run — backend-dependent, with a fallback."""
    return [str(name) for name in (results.get("generation_metrics") or JUDGE_DIMENSIONS)]


def _ret_labels(k: int) -> dict:
    return {
        "hit_rate_at_k": f"Hit rate@{k}",
        "recall_at_k": f"Recall@{k}",
        "precision_at_k": f"Precision@{k}",
        "ndcg_at_k": f"NDCG@{k}",
        "mrr": "MRR",
    }


def _grade(v: float) -> str:
    if v >= 0.85:
        return "good"
    if v >= 0.65:
        return "ok"
    return "bad"


def _when(created: str) -> str:
    try:
        d = datetime.fromisoformat(created)
    except ValueError:
        return created
    return f"{d.day} {d:%b %Y, %H:%M} {d:%Z}".strip()


def _header(title: str, meta: str) -> str:
    return f"""<header>
    <div class="brand">{_MARK}<span class="name">proofrag</span><span class="sep">/</span>
      <h1>{title}</h1></div>
    <div class="meta">{meta}</div>
  </header>"""


def _footer() -> str:
    return (
        f'<footer>Generated by <a href="https://github.com/unshDee/proofrag">proofrag</a> '
        f"{html.escape(__version__)}</footer>"
    )


def _bar(label: str, value: float) -> str:
    pct = round(value * 100)
    g = "bad" if _grade(value) == "bad" else ""
    return (
        f'<div class="bar {g}"><span>{html.escape(label)}</span>'
        f'<div class="track"><i style="width:{pct}%"></i></div><b>{pct}</b></div>'
    )


def _cell(value) -> str:
    if value is None:
        return '<span class="cell na">—</span>'
    return f'<span class="cell {_grade(value)}">{round(value * 100)}</span>'


def _pct(v) -> str:
    return "—" if v is None else f"{round(v * 100)}"


def _case(r: dict, gen: list[str], ret_labels: dict) -> str:
    s = r.get("scores") or {}
    ret = r.get("retrieval") or {}
    cells = "".join(_cell(s.get(d)) for d in gen) + _cell(ret.get("ndcg_at_k"))
    why = html.escape(str(r.get("rationale") or ""))
    answer = str(r.get("answer") or "")
    answer = html.escape(answer[:1200] + ("…" if len(answer) > 1200 else ""))
    ret_line = " · ".join(f"{ret_labels[m]} {_pct(ret.get(m))}" for m in RETRIEVAL_METRICS)
    return f"""
      <details class="case">
        <summary class="row">
          <div class="q"><span class="qt">{html.escape(str(r.get("question", "")))}</span>
            <span class="tag">{html.escape(str(r.get("difficulty", "")))}</span>
            {f'<div class="why">{why}</div>' if why else ""}</div>
          {cells}
        </summary>
        <dl class="more">
          <dt>Answer</dt><dd>{answer or '<span class="na">No answer recorded.</span>'}</dd>
          <dt>Retrieval</dt><dd>{ret_line}</dd>
        </dl>
      </details>"""


def case_mean(record: dict, gen: list[str]) -> float:
    """Mean generation score of one case; the scorecard and wizard both rank by it."""
    s = record.get("scores") or {}
    vals = [s[d] for d in gen if s.get(d) is not None]
    return sum(vals) / len(vals) if vals else 0.0


def headline(results: dict) -> tuple[int, str]:
    """Overall generation score (0-100) and a one-line verdict."""
    agg = results.get("aggregate", {})
    records = results.get("records", [])
    gen = _gen_metrics(results)
    overall = round(sum(agg.get(d, 0.0) for d in gen) / len(gen) * 100) if records and gen else 0
    flagged = sum(1 for r in records if case_mean(r, gen) < 0.65)
    if not records:
        return overall, "No cases evaluated"
    if flagged:
        return overall, f"{flagged} of {len(records)} cases need attention"
    return overall, f"All {len(records)} cases look healthy"


def render(results: dict) -> str:
    agg = results.get("aggregate", {})
    records = results.get("records", [])
    n = results.get("n", 0)
    k = results.get("k", 5)
    ret_labels = _ret_labels(k)
    gen = _gen_metrics(results)
    overall, verdict = headline(results)

    labels = {d: _gen_label(d) for d in gen} | ret_labels
    scored = [(agg[m], labels[m]) for m in labels if isinstance(agg.get(m), (int, float))]
    weakest = ""
    if records and scored:
        v, label = min(scored)
        weakest = f" Weakest metric: {html.escape(label)} ({round(v * 100)})."

    gen_names = ", ".join(_gen_label(d).lower() for d in gen)
    meta = (
        f"judge <code>{html.escape(str(results.get('judge_fingerprint', 'unknown')))}</code><br>"
        f"{html.escape(_when(str(results.get('created', ''))))} · {n} cases · k={k}"
    )
    heads = "".join(
        f'<span title="{html.escape(_gen_label(d))}">{html.escape(_gen_short(d))}</span>'
        for d in gen
    )
    cases = "".join(
        _case(r, gen, ret_labels) for r in sorted(records, key=lambda r: case_mean(r, gen))
    )

    return _TEMPLATE.format(
        css=_BASE_CSS + _REPORT_CSS,
        header=_header("RAG Eval Scorecard", meta),
        errors=_error_notice(results),
        overall=overall,
        overall_grade=_grade(overall / 100) if records else "bad",
        verdict=html.escape(verdict),
        detail=f"Overall generation quality: mean of {html.escape(gen_names)}.{weakest}",
        backend=html.escape(str(results.get("backend", "proofrag"))),
        k=k,
        gen_bars="".join(_bar(_gen_label(d), agg.get(d, 0.0)) for d in gen),
        ret_bars="".join(_bar(ret_labels[m], agg.get(m, 0.0)) for m in RETRIEVAL_METRICS),
        cols=len(gen) + 1,
        heads=heads,
        ndcg_head=html.escape(ret_labels["ndcg_at_k"]),
        cases=cases or '<p class="empty">No records.</p>',
        footer=_footer(),
    )


def write_html(results: dict, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(render(results))


def _error_notice(results: dict) -> str:
    count = len(results.get("evaluation_errors", []))
    if not count:
        return ""
    calls = "call" if count == 1 else "calls"
    return (
        f"<p class='alert' role='alert'><strong>Invalid run</strong> — {count} judge {calls} "
        "failed. Scores below are incomplete; rerun before trusting them.</p>"
    )


def render_comparison(result: dict) -> str:
    """Render a blind A/B comparison (from compare.py) to self-contained HTML."""
    a = html.escape(str(result.get("a_name", "A")))
    b = html.escape(str(result.get("b_name", "B")))
    wins = result.get("wins", {"a": 0, "b": 0, "tie": 0})
    aw, bw, tw = wins.get("a", 0), wins.get("b", 0), wins.get("tie", 0)
    # Failed calls cannot contribute evidence for either answer or a tie
    n = max(aw + bw + tw, 1)
    a_pct, b_pct = round(aw / n * 100), round(bw / n * 100)
    t_pct = max(0, 100 - a_pct - b_pct) if tw else 0
    verdict = f"{a} wins" if aw > bw else f"{b} wins" if bw > aw else "Too close to call"
    if result.get("evaluation_errors"):
        verdict = "Incomplete comparison"

    rlabels = _ret_labels(result.get("k", 5))
    ra, rb = result.get("retrieval_a", {}), result.get("retrieval_b", {})

    def better(x, y) -> str:
        return " class='num best'" if x is not None and (y is None or x > y) else " class='num'"

    ret_rows = "".join(
        f"<tr><td>{html.escape(rlabels[m])}</td>"
        f"<td{better(ra.get(m), rb.get(m))}>{_pct(ra.get(m))}</td>"
        f"<td{better(rb.get(m), ra.get(m))}>{_pct(rb.get(m))}</td></tr>"
        for m in RETRIEVAL_METRICS
    )

    badge = {
        "a": f"<span class='win wa'>{a}</span>",
        "b": f"<span class='win wb'>{b}</span>",
        "tie": "<span class='win wt'>tie</span>",
        "error": "<span class='win wf'>failed</span>",
    }
    rows = (
        "".join(
            f"<tr><td class='q'>{html.escape(str(r['question']))}"
            f"<div class='why'>{html.escape(str(r.get('reason', '')))}</div></td>"
            f"<td>{badge.get(r['winner'], '')}</td>"
            f"<td class='ans'>{html.escape(str(r.get('a_answer', ''))[:240])}</td>"
            f"<td class='ans'>{html.escape(str(r.get('b_answer', ''))[:240])}</td></tr>"
            for r in result.get("records", [])
        )
        or "<tr><td colspan='4'>No records.</td></tr>"
    )

    n_cases = result.get("n", 0)
    meta = (
        f"judge <code>{html.escape(str(result.get('judge_fingerprint', 'unknown')))}</code><br>"
        f"{html.escape(_when(str(result.get('created', ''))))} · {n_cases} cases"
    )
    return _CMP_TEMPLATE.format(
        css=_BASE_CSS + _CMP_CSS,
        header=_header("Blind A/B", meta),
        errors=_error_notice(result),
        a=a,
        b=b,
        verdict=html.escape(verdict),
        n=n_cases,
        aw=aw,
        bw=bw,
        tw=tw,
        a_pct=a_pct,
        b_pct=b_pct,
        t_pct=t_pct,
        ret_rows=ret_rows,
        rows=rows,
        footer=_footer(),
    )


def write_comparison_html(result: dict, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(render_comparison(result))


